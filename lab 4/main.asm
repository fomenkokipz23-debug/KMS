.data
    msg:     .asciz "Кількість елементів > 10: "
    array:   .word 4, 15, 22, 8, 11       # Масив за варіантом 4
    length:  .word 5                      # Кількість елементів у масиві

.text
.globl main

main:
    # 1. Друк текстового повідомлення (a7 = 4)
    la a0, msg
    li a7, 4
    ecall

    # 2. Підготовка аргументів для підпрограми
    la a0, array        # a0 = адреса початку масиву
    lw a1, length       # a1 = довжина масиву (5)

    # 3. Виклик підпрограми
    jal count_greater_10

    # 4. Друк результату (повертається у a0)
    li a7, 1
    ecall

    # 5. Завершення програми (a7 = 10)
    li a7, 10
    ecall


# =================================================================
# Підпрограма: count_greater_10
# Вхід:  a0 = адреса масиву, a1 = довжина масиву
# Вихід: a0 = кількість елементів, більших за 10
# =================================================================
count_greater_10:
    # --- Пролог: збереження s-регістрів та ra у стек за конвенцією ---
    addi sp, sp, -12
    sw ra, 8(sp)        # Зберігаємо адресу повернення
    sw s0, 4(sp)        # Зберігаємо s0
    sw s1, 0(sp)        # Зберігаємо s1

    mv s0, a0           # s0 = базовий адрес масиву
    mv s1, a1           # s1 = довжина масиву (N)

    li t0, 0            # t0 = лічильник циклу i = 0
    li t1, 0            # t1 = лічильник елементів > 10 (count = 0)
    li t4, 10           # t4 = порогове значення N = 10

loop:
    bge t0, s1, loop_end # Якщо i >= length, виходимо з циклу

    # Обчислення адреси array[i]: s0 + (i * 4)
    slli t2, t0, 2       # t2 = i * 4 (зсув у байтах)
    add t2, s0, t2       # t2 = адреса елемента array[i]
    lw t3, 0(t2)         # t3 = значення array[i]

    # Перевірка умови: якщо array[i] <= 10, пропускаємо збільшення
    ble t3, t4, skip_inc
    
    # Якщо array[i] > 10, збільшуємо лічильник
    addi t1, t1, 1

skip_inc:
    addi t0, t0, 1       # i++
    j loop               # Наступна ітерація

loop_end:
    mv a0, t1            # Записуємо результат (count) у a0 для повернення

    # --- Епілог: відновлення регістрів зі стеку ---
    lw s1, 0(sp)
    lw s0, 4(sp)
    lw ra, 8(sp)
    addi sp, sp, 12

    ret                  # Повернення (jr ra)